function applyLocale() {
  document.documentElement.lang=state.language === 'zh' ? 'zh-CN' : 'en';
  const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
  const nodes=[];
  while(walker.nextNode()) if(!['SCRIPT','STYLE'].includes(walker.currentNode.parentElement?.tagName)) nodes.push(walker.currentNode);
  nodes.forEach(node=>{
    const raw=node.nodeValue, value=raw.trim();
    if(UI_ZH[value] || UI_EN[value]) node.nodeValue=raw.replace(value,tr(value));
  });
}
